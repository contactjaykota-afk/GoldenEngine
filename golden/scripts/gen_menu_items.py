#!/usr/bin/env python3
"""Golden Engine — generate the main-menu item atlases (Sparrow format) for menu entries that
upstream FNF has no art for ("mods", "editors"). Original artwork rendered from the Inter Black
Italic font (SIL OFL). Output: golden/assets/images/mainmenu/<name>.png + .xml, with
"<name> idle" and "<name> selected" animations (3 frames each, 24 fps loop like upstream items).
Usage: golden/scripts/gen_menu_items.py   (needs Pillow)"""
import os, random
from PIL import Image, ImageDraw, ImageFont, ImageFilter

FONT = "/usr/share/fonts/opentype/inter/Inter-BlackItalic.otf"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "images", "mainmenu")
ITEMS = {"mods": "MODS", "editors": "EDITORS"}

def render(label, selected, seed):
    rnd = random.Random(seed)
    size = 118 if selected else 104
    font = ImageFont.truetype(FONT, size)
    pad = 40
    l, t, r, b = font.getbbox(label)
    w, h = r - l + pad * 2, b - t + pad * 2
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ox, oy = pad - l + rnd.randint(-2, 2), pad - t + rnd.randint(-2, 2)
    # outline / shadow
    shadow = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(shadow).text((ox + 6, oy + 8), label, font=font, fill=(40, 22, 0, 255), stroke_width=14, stroke_fill=(40, 22, 0, 255))
    img.alpha_composite(shadow)
    d = ImageDraw.Draw(img)
    outline = (255, 214, 90, 255) if selected else (92, 54, 6, 255)
    d.text((ox, oy), label, font=font, fill=outline, stroke_width=11, stroke_fill=outline)
    # vertical gradient fill
    fill = Image.new("RGBA", (w, h))
    top, bot = ((255, 255, 240), (255, 236, 160)) if selected else ((255, 226, 110), (214, 140, 20))
    for y in range(h):
        k = y / max(1, h - 1)
        fill.paste(tuple(int(top[i] + (bot[i] - top[i]) * k) for i in range(3)) + (255,), (0, y, w, y + 1))
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).text((ox, oy), label, font=font, fill=255)
    img.paste(fill, (0, 0), mask)
    if selected:
        glow = img.copy().filter(ImageFilter.GaussianBlur(10))
        base = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        base.alpha_composite(glow)
        base.alpha_composite(img)
        img = base
    return img.rotate(rnd.uniform(-1.5, 1.5), resample=Image.BICUBIC, expand=False)

def build(name, label):
    frames = [("idle", render(label, False, i)) for i in range(3)] + [("selected", render(label, True, 10 + i)) for i in range(3)]
    W = max(f.width for _, f in frames)
    H = sum(f.height for _, f in frames) + 4 * len(frames)
    sheet = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    xml = ['<?xml version="1.0" encoding="utf-8"?>', f'<TextureAtlas imagePath="{name}.png">', f'\t<!-- Generated by golden/scripts/gen_menu_items.py -->']
    y = 0
    counters = {"idle": 0, "selected": 0}
    for anim, f in frames:
        sheet.paste(f, (0, y))
        # each drawn frame is shown for 2 ticks at 24 fps (like upstream's held frames)
        for _ in range(2):
            xml.append(f'\t<SubTexture name="{name} {anim}{counters[anim]:04d}" x="0" y="{y}" width="{f.width}" height="{f.height}" />')
            counters[anim] += 1
        y += f.height + 4
    xml.append("</TextureAtlas>")
    os.makedirs(OUT, exist_ok=True)
    sheet.save(os.path.join(OUT, f"{name}.png"), optimize=True)
    open(os.path.join(OUT, f"{name}.xml"), "w").write("\n".join(xml) + "\n")
    print(name, sheet.size)

for n, l in ITEMS.items():
    build(n, l)
